export type SymbolCategory =
    | 'character' // Люди, персонажи, существа ("учитель", "волк", "старик")
    | 'location' // Локации, места, помещения ("школа", "море", "пещера")
    | 'object' // Предметы, артефакты, инструменты ("часы", "калебас", "ключ")
    | 'action' // Действия, процессы ("полет", "падение", "погоня")
    | 'nature' // Природные явления, стихии ("гроза", "затмение", "огонь")
    | 'abstract'; // Абстракции, состояния, знаки ("цифра 7", "геометрия")

export interface Interpretation {
    id?: number; // Автоинкремент ID (в IndexedDB / Postgres)
    tag: string; // "маяк", "море", "полет" (для быстрого поиска и совпадений)
    title?: string; // Заголовок ("Море / Океан")
    meaning: string; // Подробная трактовка символа

    // --- Связи ---
    sourceId: string; // Внешний ключ -> Source.id ('jung', 'custom_alexey', 'family_symbols')
    authorId?: string; // ID создателя конкретного толкования (пользователь или система)

    // --- Классификация ---
    category: SymbolCategory; // Категория символа

    // --- Оценки и Метрики ---
    rating: number; // 1.0 - 5.0 (Оценка полезности / точности толкования)
    likesCount?: number; // Количество лайков/подтверждений от пользователей
    useCount: number; // Сколько раз символ был связан со снами

    // --- Права и Модерация ---
    isCustom: boolean; // true — добавлено пользователем вручную
    isVerified?: boolean; // true — проверенное экспертом/модератором толкование

    // --- Даты ---
    createdAt: string; // ISO DateTime ('2026-08-09T14:00:00Z')
    updatedAt?: string; // ISO DateTime
}
